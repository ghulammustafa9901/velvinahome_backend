<?php

declare(strict_types=1);

use Modules\Identity\Support\PermissionCacheBootstrapper;
use Modules\Platform\Models\Domain;
use Modules\Platform\Models\Tenant;
use Modules\Platform\Tenancy\TenantDatabaseBootstrapper;
use Modules\Platform\Tenancy\TenantLogContextBootstrapper;
use Stancl\Tenancy\Bootstrappers\CacheTenancyBootstrapper;
use Stancl\Tenancy\Bootstrappers\FilesystemTenancyBootstrapper;
use Stancl\Tenancy\Bootstrappers\QueueTenancyBootstrapper;
use Stancl\Tenancy\TenantDatabaseManagers\PostgreSQLDatabaseManager;

/*
|--------------------------------------------------------------------------
| stancl/tenancy, multi-database mode (spec §4.5, ADR-0001)
|--------------------------------------------------------------------------
|
| stancl/tenancy supplies the tenant context and the bootstrappers that make the framework
| tenant-aware. It does NOT provision databases here: CreateTenant does that itself, with
| per-tenant least-privilege roles that the package's database managers do not create
| (docs/architecture/database-roles.md). Tenant resolution is also our own middleware,
| because it must select the middleware stack by domain kind (storefront / admin / api).
|
*/

$objectStorageIsLocal = env('OBJECT_STORAGE_DRIVER', 's3') === 'local';

return [
    'tenant_model' => Tenant::class,

    // Tenant ids are ULIDs generated by the model itself (ADR-0008).
    'id_generator' => null,

    'domain_model' => Domain::class,

    // Unused: identification is by our own ResolveTenantFromHost middleware, and the platform
    // host is configured in config/platform.php.
    'central_domains' => [],

    'bootstrappers' => [
        TenantDatabaseBootstrapper::class,
        CacheTenancyBootstrapper::class,
        FilesystemTenancyBootstrapper::class,
        QueueTenancyBootstrapper::class,
        TenantLogContextBootstrapper::class,
        PermissionCacheBootstrapper::class,
    ],

    'database' => [
        'central_connection' => 'landlord',
        'template_tenant_connection' => 'tenant_template',
        'prefix' => env('TENANT_DB_NAME_PREFIX', 'tenant_'),
        'suffix' => '',
        'managers' => [
            'pgsql' => PostgreSQLDatabaseManager::class,
        ],
    ],

    // Every cache key written in tenant context is tagged with the tenant, and flushing in
    // tenant context flushes only that tag — a tenant can never FLUSHDB another tenant away.
    'cache' => [
        'tag_base' => 't:',
    ],

    'filesystem' => [
        'suffix_base' => 'tenant_',
        'disks' => [
            'local',
            'public',
            'tenant_media',
            'tenant_private',
        ],
        'root_override' => [
            'local' => '%storage_path%/app/private/',
            'public' => '%storage_path%/app/public/',
            // Object storage: one bucket, one prefix per tenant (ADR-0004).
            'tenant_media' => $objectStorageIsLocal ? '%storage_path%/app/media' : 'tenants/%tenant%/media',
            'tenant_private' => $objectStorageIsLocal ? '%storage_path%/app/private-objects' : 'tenants/%tenant%/private',
        ],
        'suffix_storage_path' => true,
        // Off: Filament and Livewire assets are global. Tenant files are addressed through
        // their disk, never through asset().
        'asset_helper_tenancy' => false,
    ],

    'redis' => [
        'prefix_base' => 't:',
        'prefixed_connections' => [],
    ],

    'features' => [],

    // The package's tenant-asset route is not used; media is served from object storage.
    'routes' => false,

    'migration_parameters' => [],

    'seeder_parameters' => [],
];
